export function getPersona(key) {
  return PERSONAS.find((p) => p.key === key) || PERSONAS[0]
}

/** 给前端用的精简字段 */
export function personaBrief() {
  return PERSONAS.map((p) => ({
    key: p.key,
    name: p.name,
    tagline: p.tagline,
    desc: p.desc,
    watch: p.watch
  }))
}
